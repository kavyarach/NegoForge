import { jsPDF } from 'jspdf';

/**
 * Downloadable negotiation transcript, summary report, and PDF generator.
 */

function downloadFile(filename, content, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}

const money = (value, currency) => {
  if (value === null || value === undefined || Number.isNaN(Number(value))) {
    return 'N/A';
  }
  return `${currency}${Number(value).toLocaleString()}`;
};

const safeName = (name) =>
  String(name || 'Negotiation')
    .replace(/[^a-z0-9]+/gi, '-')
    .replace(/^-|-$/g, '');

export const ReportDownloadService = {
  /**
   * Download PDF Report using jsPDF
   */
  downloadPdfReport(report) {
    if (!report) return;

    try {
      const doc = new jsPDF();
      const {
        scenarioTitle,
        status,
        mode,
        agreementTerm,
        roundsTaken,
        currency = '₹',
        initialGap = 0,
        finalGap = 0,
        gapReductionPercentage = 0,
        negotiationScore = 0,
        agent1Metrics = {},
        agent2Metrics = {},
        takeaways = [],
        transcript = [],
      } = report;

      // Header Banner
      doc.setFillColor(15, 23, 42);
      doc.rect(0, 0, 210, 40, 'F');

      doc.setFontSize(22);
      doc.setTextColor(56, 189, 248);
      doc.text('NegoForge Negotiation Report', 14, 20);

      doc.setFontSize(11);
      doc.setTextColor(148, 163, 184);
      doc.text(`Scenario: ${scenarioTitle} | Mode: ${mode === 'PRACTICE' ? 'Human vs AI' : 'AI vs AI'}`, 14, 30);

      // Section 1: Final Status & Agreement
      let y = 52;
      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text('1. Executive Outcome Summary', 14, y);

      y += 8;
      doc.setFontSize(10);
      doc.setTextColor(71, 85, 105);
      doc.text(`Final Status: ${status === 'AGREEMENT' ? 'AGREEMENT REACHED' : status}`, 14, y);
      y += 6;
      doc.text(`Final Agreement Terms: ${agreementTerm}`, 14, y);
      y += 6;
      doc.text(`Rounds Elapsed: ${roundsTaken} | Negotiation Performance Score: ${negotiationScore}/100`, 14, y);

      // Section 2: Metrics Table
      y += 14;
      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text('2. Quantitative Convergence Metrics', 14, y);

      y += 8;
      doc.setFontSize(10);
      doc.setTextColor(71, 85, 105);
      doc.text(`Initial Gap: ${money(initialGap, currency)} | Final Gap: ${money(finalGap, currency)}`, 14, y);
      y += 6;
      doc.text(`Gap Reduction Achieved: ${gapReductionPercentage}%`, 14, y);

      // Section 3: Agent Metrics
      y += 14;
      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text('3. Participant Metrics & Satisfaction', 14, y);

      y += 8;
      doc.setFontSize(10);
      doc.text(`${agent1Metrics.name || 'Agent 1'} (${agent1Metrics.role || 'Participant'}): Objective Satisfaction ${agent1Metrics.objectiveSatisfaction || 0}%`, 14, y);
      y += 6;
      doc.text(`${agent2Metrics.name || 'Agent 2'} (${agent2Metrics.role || 'Participant'}): Objective Satisfaction ${agent2Metrics.objectiveSatisfaction || 0}%`, 14, y);

      // Section 4: Key Takeaways
      y += 14;
      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text('4. Strategic Key Takeaways', 14, y);

      y += 8;
      doc.setFontSize(9);
      takeaways.forEach((t) => {
        doc.text(`• ${t}`, 16, y);
        y += 5;
      });

      // Section 5: Timeline Excerpt
      y += 10;
      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text('5. Negotiation Transcript Excerpt', 14, y);

      y += 8;
      doc.setFontSize(8);
      transcript.slice(0, 6).forEach((evt) => {
        doc.text(`Round ${evt.round} | ${evt.agent} [${evt.action}]: ${evt.reason?.substring(0, 80)}...`, 14, y);
        y += 5;
      });

      // Footer
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(`Generated by NegoForge AI Platform on ${new Date().toLocaleString()}`, 14, 285);

      doc.save(`NegoForge-${safeName(scenarioTitle)}-Report.pdf`);
    } catch (err) {
      console.error('PDF export error:', err);
      // Fallback to text download
      this.downloadSummary(report);
    }
  },

  /**
   * Download the full round-by-round transcript txt file.
   */
  downloadTranscript(report) {
    if (!report) return;
    const { scenarioTitle, status, transcript = [], currency = '₹' } = report;

    let content = 'NEGOFORGE\nFULL NEGOTIATION TRANSCRIPT\n========================================\n\n';
    content += `Scenario: ${scenarioTitle}\nFinal Status: ${status}\nTotal Events: ${transcript.length}\n\n========================================\n\n`;

    transcript.forEach((event, index) => {
      content += `EVENT ${index + 1}\n----------------------------------------\n`;
      content += `Round: ${event.round ?? '-'}\n`;
      content += `Agent: ${event.agent ?? 'Unknown'}\n`;
      content += `Action: ${event.action ?? '-'}\n`;
      if (event.decision) content += `Decision: ${event.decision}\n`;
      if (event.offer) content += `Offer: ${money(event.offer.value, currency)}\n`;
      if (event.reason) content += `Reason: ${event.reason}\n`;
      if (event.timestamp) content += `Timestamp: ${new Date(event.timestamp).toLocaleString()}\n`;
      content += '\n';
    });

    downloadFile(`NegoForge-${safeName(scenarioTitle)}-Transcript.txt`, content);
  },

  /**
   * Download structured summary text file.
   */
  downloadSummary(report) {
    if (!report) return;
    const {
      scenarioTitle,
      status,
      mode,
      agreementTerm,
      roundsTaken,
      currency = '₹',
      initialGap,
      finalGap,
      gapReductionPercentage,
      negotiationScore,
      takeaways = [],
      generatedAt,
    } = report;

    const content = `
NEGOFORGE - NEGOTIATION SUMMARY REPORT
========================================
Scenario: ${scenarioTitle}
Mode: ${mode === 'PRACTICE' ? 'Human vs AI' : 'AI vs AI'}
Final Status: ${status}
Final Agreement: ${agreementTerm}
Rounds Elapsed: ${roundsTaken}

========================================
METRICS
Initial Gap: ${money(initialGap, currency)}
Final Gap: ${money(finalGap, currency)}
Gap Reduction: ${gapReductionPercentage}%
Negotiation Score: ${negotiationScore}/100

========================================
TAKEAWAYS
${takeaways.map((item, index) => `${index + 1}. ${item}`).join('\n')}

Generated by NegoForge at ${new Date(generatedAt || Date.now()).toLocaleString()}
`.trim();

    downloadFile(`NegoForge-${safeName(scenarioTitle)}-Summary.txt`, content);
  },

  /**
   * Download JSON complete report file.
   */
  downloadCompleteReport(report) {
    if (!report) return;
    downloadFile(`NegoForge-${safeName(report.scenarioTitle)}-Complete-Report.json`, JSON.stringify(report, null, 2), 'application/json');
  },
};